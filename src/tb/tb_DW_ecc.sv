`timescale 1ns/1ps

module tb_DW_ecc;

//-----------------------------------------------------------------------------
// 参数定义 - 可根据需要修改
//-----------------------------------------------------------------------------
parameter integer WIDTH     = 96;   // 数据宽度
parameter integer CHKBITS   = 8;    // 校验位宽度
parameter integer SYND_SEL  = 0;    // 校正子选择参数

//-----------------------------------------------------------------------------
// 信号声明 - 与 DW_ecc 模块端口一一对应
//-----------------------------------------------------------------------------
reg                  gen;          // 校验位生成控制输入（高电平有效）
reg                  correct_n;    // 错误校正控制输入（低电平有效）
reg  [WIDTH-1:0]     datain;       // 数据输入总线
reg  [CHKBITS-1:0]   chkin;        // 校验位输入总线

wire                 err_detect;   // 错误检测输出标志（高电平有效）
wire                 err_multpl;   // 多位错误检测输出（高电平有效）
wire [WIDTH-1:0]     dataout;      // 数据输出总线
wire [CHKBITS-1:0]   chkout;       // 校验位输出总线

//-----------------------------------------------------------------------------
// 可选：添加时钟和复位信号（如果您的测试逻辑需要）
//-----------------------------------------------------------------------------
reg                  clk;          // 系统时钟
reg                  rst_n;        // 系统复位（低电平有效）
reg [CHKBITS-1:0]    ecc_r;

// 生成 100MHz 时钟（周期 10ns）
initial begin
    clk = 1'b0;
    forever #5 clk = ~clk;
end

// 复位信号生成
initial begin
    rst_n = 1'b0;
    #20 rst_n = 1'b1;
end

//-----------------------------------------------------------------------------
// DW_ecc 模块实例化与连线
//-----------------------------------------------------------------------------
DW_ecc #(
    .width      (WIDTH),
    .chkbits    (CHKBITS),
    .synd_sel   (SYND_SEL)
) u_DW_ecc (
    .gen        (gen),
    .correct_n  (correct_n),
    .datain     (datain),
    .chkin      (chkin),
    .err_detect (err_detect),
    .err_multpl (err_multpl),
    .dataout    (dataout),
    .chkout     (chkout)
);

always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
        ecc_r <= 0;
    end else begin
        ecc_r <= chkout;
    end
end

//-----------------------------------------------------------------------------
// 测试逻辑区域 - 请在此处添加您的测试代码
//-----------------------------------------------------------------------------
initial begin
    // 初始化所有输入信号
    gen         = 1'b0;
    correct_n   = 1'b1;  // 默认不进行错误校正
    datain      = {WIDTH{1'b0}};
    chkin       = {CHKBITS{1'b0}};

    // 等待复位完成
    @(posedge rst_n);
    #10;

    // ==============================================
    // 示例测试点1：生成校验位
    // ==============================================
    // 您的代码：设置datain，置gen=1，观察chkout输出
    datain = 96'h111122223333444455556666;
    gen = 1'b1;

    // ==============================================
    // 示例测试点2：无错误数据检测
    // ==============================================
    // 您的代码：置gen=0，输入正确的datain和chkin，观察err_detect和err_multpl
    #100;
    gen = 1'b0;
    datain = 96'h111122223333444455556666;
    chkin = ecc_r;

    // ==============================================
    // 示例测试点3：单比特错误检测与校正
    // ==============================================
    // 您的代码：在datain或chkin中引入1位错误，置correct_n=0，观察dataout和err_detect
    #100;
    correct_n = 1'b0;
    datain = 96'h101122223333444455556666;

    // ==============================================
    // 示例测试点4：多比特错误检测
    // ==============================================
    // 您的代码：在datain或chkin中引入2位或更多错误，观察err_multpl输出
    #100;
    datain = 96'h100122223333444455556666;
    
    #100;
    datain = 96'h100022223333444455556666;
    
    #100;
    chkin = ecc_r ^ 8'h80;
    datain = 96'h111122223333444455556666;

    // ==============================================
    // 测试结束
    // ==============================================
    #100;
    $display("测试完成！");
    $finish;
end

endmodule